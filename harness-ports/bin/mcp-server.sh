#!/usr/bin/env bash
# MCP server launcher — one entry point, no machine-specific path committed.
#
# Codex forwards environment variable NAMES to an MCP child (`env_vars`); it does
# NOT expand ${VAR} inside `command`/`args` (codex-rs/config/src/mcp_types.rs).
# Hermes DOES expand ${VAR}. Rather than commit two different escaping schemes —
# and rather than hardcode this sandbox's /root/venv-agent-factory, which is wrong on
# the PC — every server launches through this script, which resolves paths from
# env vars with non-root defaults.
#
# Override per machine (export before starting the harness, or set them in the
# harness's own env block):
#   AF_REPO          repo root                  default: git toplevel
#   AF_VENV          python venv root           default: $HOME/venv-agent-factory
#   CODEBASE_MEMORY_BIN   codebase-memory-mcp path   default: $HOME/.local/bin/codebase-memory-mcp
#   GRAFT_BIN             graft binary               default: graft (from PATH)
#   OUROBOROS_BIN         ouroboros binary           default: ouroboros (from PATH)
#
# Usage: mcp-server.sh <gitnexus|aleph|codebase-memory|ouroboros|graft>
# phoenix-docs is an HTTP server — it has no launcher, it is a URL in the config.
#
# Fails LOUD: an unknown server name or a missing binary exits non-zero with a
# message on stderr. A launcher that exits 0 having started nothing would present
# as "server configured" while no tool ever appears.
set -euo pipefail

NAME="${1:-}"
if [ -z "$NAME" ]; then
  echo "mcp-server.sh: no server name given" >&2
  exit 64
fi

if [ -z "${AF_REPO:-}" ]; then
  # NOT `git ... || cd ... && pwd`: that parses as (git||cd)&&pwd, so on the
  # success path pwd runs too and AF_REPO becomes TWO lines. Bit live here
  # 2026-09-01 — the gitnexus launcher printed a doubled path.
  AF_REPO="$(git rev-parse --show-toplevel 2>/dev/null)"
  if [ -z "$AF_REPO" ]; then
    AF_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
  fi
fi
: "${AF_VENV:=$HOME/venv-agent-factory}"
: "${CODEBASE_MEMORY_BIN:=$HOME/.local/bin/codebase-memory-mcp}"
: "${GRAFT_BIN:=graft}"
: "${OUROBOROS_BIN:=ouroboros}"
export AF_REPO

need() {
  if ! command -v "$1" >/dev/null 2>&1 && [ ! -x "$1" ]; then
    echo "mcp-server.sh: '$1' not found — MCP server '$NAME' did NOT start." >&2
    echo "  Set the matching override (see the header of this script)." >&2
    exit 69
  fi
}

case "$NAME" in
  gitnexus)
    need node
    # .gitnexus/run.cjs is generated by `npx gitnexus analyze`, not committed.
    # A fresh clone (and a git worktree, which does not carry it) will not have
    # it. Say that plainly instead of letting node throw a module-resolution
    # stack trace that reads like a broken config.
    if [ ! -f "$AF_REPO/.gitnexus/run.cjs" ]; then
      echo "mcp-server.sh: $AF_REPO/.gitnexus/run.cjs missing — gitnexus MCP did NOT start." >&2
      echo "  Generate it in that clone first: cd \"$AF_REPO\" && npx gitnexus analyze" >&2
      echo "  (Tier-2 fallback meanwhile: python3 \"$AF_REPO/scripts/gn_mcp.py\")" >&2
      exit 69
    fi
    exec node "$AF_REPO/.gitnexus/run.cjs" mcp
    ;;
  aleph)
    need "$AF_VENV/bin/aleph"
    export ALEPH_WORKSPACE="$AF_REPO"
    exec "$AF_VENV/bin/aleph" --workspace-mode any --tool-docs concise
    ;;
  codebase-memory)
    need "$CODEBASE_MEMORY_BIN"
    exec "$CODEBASE_MEMORY_BIN"
    ;;
  ouroboros)
    # Tier 1. On the documented `mcp serve` breakage (MCP-SDK v2 vs the
    # [claude-sdk] extra's v1.x) use the tier-2 stdio wrapper instead:
    #   python3 "$AF_REPO/scripts/ooo_mcp.py" <tool> '<json-args>'
    need "$OUROBOROS_BIN"
    exec "$OUROBOROS_BIN" mcp serve
    ;;
  graft)
    need "$GRAFT_BIN"
    exec "$GRAFT_BIN" mcp "$AF_REPO"
    ;;
  *)
    echo "mcp-server.sh: unknown server '$NAME'" >&2
    echo "  known: gitnexus aleph codebase-memory ouroboros graft" >&2
    echo "  (phoenix-docs is HTTP — configure its URL directly, no launcher)" >&2
    exit 64
    ;;
esac
