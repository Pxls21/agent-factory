#!/usr/bin/env python3
"""Generate the per-harness lane-role artifacts from ONE source of truth.

Source : harness-ports/roles/<name>.md      (harness-neutral role body)
Emits  : .codex/agents/<name>.toml          (Codex role config layer)

Why a generator rather than two hand-maintained copies: Codex's role prompt is a
TOML string field (`developer_instructions`), not a file path, so the body has to
be embedded. Embedding it by hand would guarantee drift the first time a role
changes. The .md is authoritative; the TOML is derived and regenerated.

Codex role mechanism, from primary source (openai/codex @ bc39b0e):
  config/src/config_toml.rs — `[agents.<name>]` roles map to AgentRoleToml
    { description, config_file, nickname_candidates }; `config_file` is "a
    role-specific config layer" resolved relative to the config.toml declaring it.
  config/src/config_toml.rs:228 — `developer_instructions` is "Developer
    instructions inserted as a `developer` role message" — the correct home for a
    role persona. (`instructions` replaces the system prompt and
    `experimental_instructions_file` is explicitly discouraged upstream; neither
    is right for a role.)

Hermes has NO user-definable role mechanism (see docs/HARNESS-PORTS.md), so its
lanes consume harness-ports/roles/<name>.md directly — pc-lane.sh prepends it.

Usage:  python3 harness-ports/bin/build-roles.py [--check]
  --check  verify the generated TOMLs match the sources; exit 1 on drift.
"""
import subprocess
import sys
from pathlib import Path


def repo_root() -> Path:
    try:
        p = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                           capture_output=True, text=True, timeout=5)
        if p.returncode == 0 and p.stdout.strip():
            return Path(p.stdout.strip())
    except Exception as e:  # fail-LOUD: say which root we fell back to and why
        print(f"build-roles: git rev-parse failed ({e}) — using the script-relative repo root", file=sys.stderr)
    return Path(__file__).resolve().parents[2]


ROLES = {
    "code-implementer": "The BUILD lane: turns a settled design into verified code, "
                        "proves it mechanically, and escalates rather than improvises "
                        "when reality contradicts the brief.",
    "adversarial-verifier": "The VERIFY lane: attacks a finished increment against the "
                            "FULL contract, reproduces every claim it relies on, and "
                            "returns MERGE-READY / NOT-READY with evidence.",
    "evidence-gatherer": "The EXPLORE lane: collects exhaustive file:line-cited evidence "
                         "WITHOUT concluding. It must not propose root causes, verdicts, "
                         "or fixes.",
}


def toml_multiline(s: str) -> str:
    """Embed a body in a TOML basic multi-line string, safely.

    Escapes backslashes and any run of three-or-more quotes that would close the
    literal early. Trailing whitespace before the terminator is avoided with a
    leading line-continuation backslash so the body starts flush.
    """
    s = s.replace("\\", "\\\\")
    s = s.replace('"""', '\\"\\"\\"')
    if s.endswith('"'):
        s = s[:-1] + '\\"'
    return '"""\\\n' + s + '"""'


def build(root: Path) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for name, desc in ROLES.items():
        body = (root / "harness-ports" / "roles" / f"{name}.md").read_text()
        out[root / ".codex" / "agents" / f"{name}.toml"] = (
            f"# GENERATED by harness-ports/bin/build-roles.py — DO NOT EDIT.\n"
            f"# Source of truth: harness-ports/roles/{name}.md\n"
            f"# Regenerate:  python3 harness-ports/bin/build-roles.py\n"
            f"# Verify:      python3 harness-ports/bin/build-roles.py --check\n"
            f"#\n"
            f"# Codex applies this as a role-specific config layer for\n"
            f"# `[agents.{name}]` in .codex/config.toml. No model is pinned here:\n"
            f"# the PC harness serves ONE model, so the coordinator-side routing\n"
            f"# table does not apply (docs/HARNESS-PORTS.md).\n\n"
            f"developer_instructions = {toml_multiline(body)}\n"
        )
    return out


def main() -> int:
    root = repo_root()
    check = "--check" in sys.argv
    planned = build(root)
    drift = []
    for path, text in planned.items():
        current = path.read_text() if path.is_file() else None
        if current == text:
            continue
        drift.append(path.relative_to(root))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check:
        if drift:
            print("DRIFT — regenerate with build-roles.py:")
            for d in drift:
                print(f"  {d}")
            return 1
        print(f"OK: {len(planned)} role config layers match their sources")
        return 0
    print(f"wrote {len(drift)} of {len(planned)} role config layers"
          + (f": {[str(d) for d in drift]}" if drift else " (all already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
